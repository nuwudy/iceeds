    /**
     * Get courses filtered by category ID.
     */
    public static function getCoursesByCategory(string $categoryId): array
    {
        $all = self::getCourses();
        if ($categoryId === 'all') {
            return $all;
        }

        return array_values(array_filter($all, fn($item) => $item['category'] === $categoryId));
    }

    /**
     * Find a single course by its slug.
     */
    public static function findCourse(string $slug): ?array
    {
        foreach (self::getCourses() as $course) {
            if ($course['slug'] === $slug) {
                return $course;
            }
        }
        return null;
    }
